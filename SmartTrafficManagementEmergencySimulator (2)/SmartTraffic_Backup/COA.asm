; 8086 / MASM-style COA demonstration
.MODEL SMALL
.STACK 100H
.DATA
    VEHICLE_COUNT DB 18
    THRESHOLD     DB 10
    PRIORITY      DB 0
.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX
    MOV AL, VEHICLE_COUNT
    CMP AL, THRESHOLD
    JBE NORMAL_TRAFFIC
    MOV PRIORITY, 1
    JMP FINISH
NORMAL_TRAFFIC:
    MOV PRIORITY, 0
FINISH:
    MOV AH, 4CH
    INT 21H
MAIN ENDP
END MAIN
